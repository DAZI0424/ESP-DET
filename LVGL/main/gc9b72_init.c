esp_err_t gc9b72_panel_init(esp_lcd_panel_io_handle_t io)
{
    ESP_RETURN_ON_FALSE(io != NULL, ESP_ERR_INVALID_ARG, TAG, "panel IO is NULL");

    size_t offset = 0;
    while (offset + 1 < sizeof(s_init_commands)) {
        const uint8_t command = s_init_commands[offset++];
        const uint8_t length_flags = s_init_commands[offset++];
        if (command == GC9B72_END_CMD && length_flags == GC9B72_END_LEN) {
            ESP_LOGI(TAG, "JKC319I002 vendor initialization sent");
            return ESP_OK;
        }

        const size_t data_length = length_flags & ~GC9B72_DELAY_FLAG;
        ESP_RETURN_ON_FALSE(offset + data_length <= sizeof(s_init_commands),
                            ESP_ERR_INVALID_SIZE, TAG, "invalid init command table");
        const uint8_t *data = data_length > 0 ? &s_init_commands[offset] : NULL;
        ESP_RETURN_ON_ERROR(esp_lcd_panel_io_tx_param(io, command, data, data_length),
                            TAG, "command 0x%02X failed", command);
        offset += data_length;

        if ((length_flags & GC9B72_DELAY_FLAG) != 0) {
            ESP_RETURN_ON_FALSE(offset < sizeof(s_init_commands), ESP_ERR_INVALID_SIZE,
                                TAG, "missing init delay");
            vTaskDelay(pdMS_TO_TICKS(s_init_commands[offset++]));
        }
    }

    return ESP_ERR_INVALID_SIZE;
}
